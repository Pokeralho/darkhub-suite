// Generates docs/hub/BUILTIN.md (every DarkHub tweak a package can reference with "use", with what it writes, and every
// operation it can run with "op") and docs/hub/builtins.json (the same list for the Hub server's validator).
// Run: npm run hub:docs (tests fail when the files are out of date).
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
import { buildBuiltins, builtinsJson } from '../electron/services/hub/builtins.js'

const { default: engine } = await import(new URL('../electron/services/optimizer/DeepTweaksEngine.js', import.meta.url))
const { default: optimizer } = await import(new URL('../electron/services/optimizer/SystemOptimizerService.js', import.meta.url))

const CATEGORY = {
  customization: 'Interface and Explorer', privacy: 'Privacy', gaming: 'Gaming', storage: 'Storage', system: 'System', network: 'Network', power: 'Power'
}
const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\r?\n/g, ' ')
const value = (c) => (c.deleteKey ? 'delete key' : c.deleteValue ? 'delete value' : `${c.type} = ${c.data}`)

export function builtinMarkdown() {
  const tweaks = engine.listTweaks()
  const lines = [
    '<!-- GENERATED by scripts/hub-docs.mjs from electron/services/optimizer/DeepTweaksEngine.js. Do not edit: run `npm run hub:docs`. -->',
    '',
    '# Built-in DarkHub tweaks and operations',
    '',
    'A package uses one of these with `{ "use": "darkhub:<id>" }`. DarkHub applies it with its own definition, snapshot and revert,',
    'and when the package is removed it only undoes the tweaks the package turned on (not the ones the user already had).',
    '',
    'Tweaks marked **official only** touch security and are refused in community packages.',
    '',
    `${tweaks.length} tweaks.`,
    ''
  ]
  const byCat = new Map()
  for (const t of tweaks) { if (!byCat.has(t.category)) byCat.set(t.category, []); byCat.get(t.category).push(t) }
  for (const [cat, list] of byCat) {
    lines.push(`## ${CATEGORY[cat] || cat}`, '')
    for (const t of list) {
      const flags = [
        `risk: ${t.risk}`,
        t.securityRelated ? '**official only**' : null,
        t.requiresReboot ? 'needs restart' : null,
        t.explorerRestart ? 'restarts Explorer' : null,
        t.hasCommands ? 'also runs a DarkHub command' : null,
        t.recommended ? 'recommended' : null
      ].filter(Boolean).join(' · ')
      lines.push(`### \`darkhub:${t.id}\``, '', `**${cell(t.title)}** · ${flags}`, '')
      if (t.description) lines.push(cell(t.description), '')
      const changes = (t.changes || []).filter(Boolean)
      if (changes.length) {
        lines.push('| Key | Value name | Writes |', '|---|---|---|')
        for (const c of changes) lines.push(`| \`${cell(c.key)}\` | \`${cell(c.name || '(Default)')}\` | ${cell(value(c))} |`)
        lines.push('')
      }
    }
  }
  const builtins = buildBuiltins(engine, optimizer)
  const ops = [...builtins].filter(([, b]) => b.kind === 'op')
  const USE = { yes: 'any package', official: '**official only**', no: '**not allowed in packages**' }
  lines.push(
    '# Operations',
    '',
    'A package runs one of these with `{ "op": "darkhub:op:<id>" }`. Reversible operations are undone on uninstall with their own',
    'revert (and are skipped, and not undone, when they were already active). One-time actions (cleanup, DNS flush) just run.',
    'Operations that only wrap built-in tweaks are installed as those tweaks.',
    '',
    `${ops.length} operations.`,
    ''
  )
  for (const [id, b] of ops) {
    const flags = [
      `risk: ${b.risk}`,
      b.reversible ? 'reversible' : 'one-time action',
      USE[b.packageUse],
      b.requiresReboot ? 'needs restart' : null,
      b.tweakIds ? `= ${b.tweakIds.map((t) => `\`darkhub:${t}\``).join(', ')}` : null
    ].filter(Boolean).join(' · ')
    lines.push(`### \`darkhub:${id}\``, '', `**${cell(b.title)}** · ${flags}`, '')
    if (b.description) lines.push(cell(b.description), '')
  }
  return `${lines.join('\n').trimEnd()}\n`
}

export function builtinJsonText() {
  return `${JSON.stringify(builtinsJson(buildBuiltins(engine, optimizer)), null, 1)}\n`
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = path.join(root, 'docs', 'hub', 'BUILTIN.md')
  fs.mkdirSync(path.dirname(out), { recursive: true })
  fs.writeFileSync(out, builtinMarkdown())
  const json = path.join(root, 'docs', 'hub', 'builtins.json')
  fs.writeFileSync(json, builtinJsonText())
  console.log(`wrote ${path.relative(root, out)} and ${path.relative(root, json)}`)
}
